/**
 * Makes a tiny blurred preview of every picture in public/home and writes them to
 * src/features/cms/blur-data.ts. Run again whenever those pictures change.
 *   npx tsx scripts/generate-blur-data.ts
 */
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = new URL("../public/home/", import.meta.url).pathname;

async function main() {
  const entries: [string, string][] = [];
  const walk = async (dir: string, prefix: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        await walk(full, `${prefix}${entry.name}/`);
        continue;
      }
      if (!/\.(webp|png|jpe?g)$/i.test(entry.name) || entry.name.startsWith("tyre")) continue;
      const buffer = await sharp(full).resize({ width: 16 }).webp({ quality: 40 }).toBuffer();
      entries.push([`/home/${prefix}${entry.name}`, `data:image/webp;base64,${buffer.toString("base64")}`]);
    }
  };
  await walk(root, "");
  entries.sort(([a], [b]) => a.localeCompare(b));
  const body = entries.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join("\n");
  writeFileSync(
    new URL("../src/features/cms/blur-data.ts", import.meta.url),
    `// Generated by scripts/generate-blur-data.ts. Do not edit by hand.\nexport const blurData: Record<string, string> = {\n${body}\n};\n\n/** The blurred preview for one of the site's own pictures, if there is one. */\nexport const blurFor = (src: string) => blurData[src];\n`,
  );
  console.log(`wrote ${entries.length} previews`);
}

main();
